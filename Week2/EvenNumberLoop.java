package Week2;
public class EvenNumberLoop {
    public static void main(String[] args){
        // Creating variable
        int LoopNumber = 0;
        // While loop that prints variable then adds 2 to ensure even numbers.
        while (LoopNumber != 22){
            System.out.println(LoopNumber);
            LoopNumber = LoopNumber + 2;
        }
    }
}
